/**
 * Bundles the vertical's published artifacts into src/generated/, as the
 * first step of `npm run build`:
 *
 *   - every frozen JSON Schema under commerce/schemas/<type>/v<version>.json,
 *     verbatim, keyed by its `$id` (schemas.ts), plus the list of ids alone
 *     (schema-ids.ts), which is all the library needs at run time;
 *   - the release manifest, commerce/spec/releases.json (release-manifest.ts);
 *   - the data-block property inventory PDP-I-001 reads, taken from the
 *     Product Sheet schema of the latest release (schema-properties.ts).
 *
 * Nothing in src/generated/ is checked in: the frozen files are the
 * source, and a schema added under commerce/schemas/ is bundled by the
 * next build with no further step. The script refuses a schema whose
 * `$id` does not match its path, since the path is the published URL.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const commerce = join(here, "..", "..");
const schemasDir = join(commerce, "schemas");
const out = join(here, "..", "src", "generated");

const manifest = JSON.parse(readFileSync(join(commerce, "spec", "releases.json"), "utf8"));
const urlFor = (sheet, version) =>
  manifest.schema_url_template.replace("{sheet}", sheet).replace("{version}", version);

const schemas = {};
for (const type of readdirSync(schemasDir, { withFileTypes: true })) {
  if (!type.isDirectory()) continue;
  for (const file of readdirSync(join(schemasDir, type.name)).sort()) {
    const match = /^v(\d+(?:\.\d+)*)\.json$/.exec(file);
    if (match === null) throw new Error(`commerce/schemas/${type.name}/${file}: not a v<version>.json file`);
    const schema = JSON.parse(readFileSync(join(schemasDir, type.name, file), "utf8"));
    const expected = urlFor(type.name, match[1]);
    if (schema.$id !== expected) {
      throw new Error(`commerce/schemas/${type.name}/${file}: $id is ${schema.$id}, expected ${expected}`);
    }
    schemas[schema.$id] = schema;
  }
}

const latest = manifest.releases[manifest.releases.length - 1];
const latestProduct = schemas[urlFor("product", latest.sheets.product)];
if (latestProduct === undefined) {
  throw new Error(`no frozen schema for Product Sheet spec ${latest.sheets.product} (release ${latest.release})`);
}
const dataBlockProperties = Object.keys(latestProduct.$defs.dataBlock.properties).sort();

const banner = "// Generated by scripts/bundle-schemas.mjs; do not edit, do not commit.\n";
const json = (value) => JSON.stringify(value, null, 2);
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "schemas.ts"),
  `${banner}export const SCHEMAS: Readonly<Record<string, Record<string, unknown>>> =\n${json(schemas)};\n`
);
writeFileSync(
  join(out, "schema-ids.ts"),
  `${banner}export const SCHEMA_IDS: readonly string[] = ${json(Object.keys(schemas))};\n`
);
writeFileSync(
  join(out, "release-manifest.ts"),
  `${banner}export const RELEASE_MANIFEST =\n${json(manifest)} as const;\n`
);
writeFileSync(
  join(out, "schema-properties.ts"),
  `${banner}export const DATA_BLOCK_PROPERTIES: readonly string[] = ${json(dataBlockProperties)};\n`
);
console.log(`bundled ${Object.keys(schemas).length} schemas from commerce/schemas/`);

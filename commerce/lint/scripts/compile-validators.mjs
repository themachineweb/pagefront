/**
 * Generates dist/schema-validators.js: the Layer 1 validators for the
 * product and organization schemas, compiled ahead of time with Ajv's
 * standalone mode. Runs after tsc (it reads the bundled schemas from
 * dist/), as the second half of `npm run build`.
 *
 * Why ahead of time: Ajv compiles a schema into JavaScript source and
 * evaluates it, which environments without runtime code generation,
 * Cloudflare Workers and pages under a strict Content Security Policy
 * among them, refuse. The generated module is plain functions; it needs
 * only Ajv's runtime helpers and ajv-formats' format table.
 *
 * Ajv's ES-module output still reaches those two through `require`,
 * which an ES module cannot call, so the two expressions are rewritten
 * to imports. The header records a digest of the schemas so
 * test/schema-validators.test.mjs can tell when the file is stale.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020Module from "ajv/dist/2020.js";
import addFormatsModule from "ajv-formats";
import standaloneCodeModule from "ajv/dist/standalone/index.js";

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module;
const addFormats = addFormatsModule.default ?? addFormatsModule;
const standaloneCode = standaloneCodeModule.default ?? standaloneCodeModule;

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "..", "dist");

const { SCHEMAS } = await import(join(dist, "generated", "schemas.js"));

export const schemaDigest = (...schemas) => {
  const hash = createHash("sha256");
  schemas.forEach((schema, index) => {
    if (index > 0) hash.update("\n");
    hash.update(JSON.stringify(schema));
  });
  return hash.digest("hex");
};

/** Every bundled schema, in the order the digest covers them. */
export const BUNDLED_SCHEMAS = Object.values(SCHEMAS);

/** `…/commerce/product/v0.9.0.json` → `validate_product_v0_9_0`. */
const exportName = (id) =>
  "validate_" + new URL(id).pathname.replace(/^.*\/commerce\//, "").replace(/\.json$/, "").replace(/[^A-Za-z0-9]/g, "_");

// The same options validate-and-lint.ts used when it compiled at load
// time: every error reported, union `type` keywords allowed.
const ajv = new Ajv2020({
  allErrors: true,
  allowUnionTypes: true,
  code: { source: true, esm: true },
});
addFormats(ajv);
const names = {};
for (const schema of BUNDLED_SCHEMAS) {
  ajv.addSchema(schema);
  names[exportName(schema.$id)] = schema.$id;
}

let code = standaloneCode(ajv, names);

const PRELUDE = '"use strict";';
if (!code.startsWith(PRELUDE)) throw new Error("unexpected standalone output: no prelude");
code = code.slice(PRELUDE.length);

const REWRITES = [
  ['require("ajv/dist/runtime/ucs2length").default', "ucs2length"],
  ['require("ajv-formats/dist/formats").fullFormats', "fullFormats"],
];
for (const [from, to] of REWRITES) code = code.split(from).join(to);
const leftover = code.match(/require\("[^"]*"\)/);
if (leftover) throw new Error(`unrewritten require in standalone output: ${leftover[0]}`);

// Both helpers are CommonJS modules flagged __esModule. Node hands a
// default import their module.exports object (the function sits on
// .default); esbuild hands it exports.default itself. The header
// accepts either, and takes the formats table as a named import, which
// every loader resolves the same way.
const header = `// Generated by scripts/compile-validators.mjs; do not edit.
// schemas sha256 ${schemaDigest(...BUNDLED_SCHEMAS)}
import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";
import { fullFormats } from "ajv-formats/dist/formats.js";
const ucs2length = typeof ucs2lengthModule === "function" ? ucs2lengthModule : ucs2lengthModule.default;
`;
const registry =
  "export const VALIDATORS = {\n" +
  Object.entries(names).map(([name, id]) => `  ${JSON.stringify(id)}: ${name},`).join("\n") +
  "\n};\n";
writeFileSync(join(dist, "schema-validators.js"), header + code + "\n" + registry);
writeFileSync(
  join(dist, "schema-validators.d.ts"),
  readFileSync(join(here, "..", "src", "schema-validators.d.ts"), "utf8")
);
